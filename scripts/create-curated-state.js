function buildMakerSystemPrompt(profile) {
  return [
    "너는 학습 데이터 제작 도우미다.",
    "사용자가 제공한 핵심 사실만 사용해서 답변 초안을 만든다.",
    "핵심 사실에 없는 정보는 추가하지 않는다.",
    "모든 답변은 한국어로만 작성한다.",
    "아래 원하는 말투와 형식을 프로필 기본 말투보다 우선한다.",
    `원하는 말투와 형식:\n${makerStyle}`,
    `AI 역할 참고: ${profile.role}`,
    `프로필 답변 스타일 참고: ${profile.style}`,
  ].join("\n");
}

function buildMakerUserInput(example) {
  return [
    `질문:\n${example.question}`,
    "",
    `핵심 사실:\n${example.facts.map((fact) => `- ${fact}`).join("\n")}`,
    "",
    `원하는 말투/형식:\n${makerStyle}`,
    "",
    "위 핵심 사실만 사용해서 학습 데이터로 쓸 답변을 만들어줘.",
  ].join("\n");
}

function loadPreviousState() {
  if (!fs.existsSync(statePath)) {
    return null;
  }

  return JSON.parse(fs.readFileSync(statePath, "utf8"));
}

function createDataset(profile) {
  const createdAtBase = Date.now();
  const systemPrompt = buildMakerSystemPrompt(profile);

  return examples.map((example, index) => ({
    id: `curated-dataset-${String(index + 1).padStart(2, "0")}`,
    profileId: profile.id,
    profileName: profile.name,
    createdAt: new Date(createdAtBase + index * 1000).toISOString(),
    source: "curated",
    messages: [
      {
        role: "system",
        content: systemPrompt,
      },
      {
        role: "user",
        content: buildMakerUserInput(example),
      },
      {
        role: "assistant",
        content: example.answer,
      },
    ],
  }));
}

const previousState = loadPreviousState();
if (examples.length !== 50) {
  throw new Error(`Curated dataset must contain exactly 50 examples. Current: ${examples.length}`);
}

const previousProfile = previousState?.profiles?.find((profile) => profile.id === "profile-nabi") ?? previousState?.profiles?.[0];
const profile = {
  ...fallbackProfile,
  ...(previousProfile ?? {}),
  ...fallbackProfile,
  messages: [],
  memories: previousProfile?.memories ?? [],
};

const state = {
  profiles: [profile],
  activeProfileId: profile.id,
  settings: previousState?.settings ?? {
    provider: "ollama",
    model: "qwen2.5:7b",
  },
  dataset: createDataset(profile),
  failures: previousState?.failures ?? [],
};

fs.mkdirSync(dataDir, { recursive: true });
fs.writeFileSync(statePath, `${JSON.stringify(state, null, 2)}\n`, "utf8");

